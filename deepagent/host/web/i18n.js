function t(text, values = {}) {
  const label = language === 'en' ? english[text] || text : text;
  return label.replace(/\{(\w+)\}/g, (_, key) => values[key] ?? '{' + key + '}');
}
function setLabel(element, text, values = {}) {
  element.dataset.i18n = text; element.i18nValues = values; element.textContent = t(text, values);
}
function setLanguage(value) {
  language = value === 'en' ? 'en' : 'zh';
  document.documentElement.lang = language === 'en' ? 'en' : 'zh-CN';
  document.title = t('DeepAgent · 静海');
  try { localStorage.language = language; } catch { /* The switch still works without storage. */ }
  document.querySelectorAll('[data-tool-status]').forEach(element => element.i18nValues.status = t(element.dataset.toolStatus));
  document.querySelectorAll('[data-i18n]').forEach(element => setLabel(element, element.dataset.i18n, element.i18nValues));
  for (const [key, attribute] of [['i18nPlaceholder', 'placeholder'], ['i18nLabel', 'aria-label'], ['i18nEmpty', 'data-empty'], ['i18nRole', 'data-role']]) {
    const selector = '[data-' + key.replace(/[A-Z]/g, letter => '-' + letter.toLowerCase()) + ']';
    document.querySelectorAll(selector).forEach(element => element.setAttribute(attribute, t(element.dataset[key])));
  }
  const button = document.getElementById('language');
  button.textContent = language === 'en' ? '中文' : 'EN';
  button.setAttribute('aria-label', language === 'en' ? '切换为中文' : 'Switch to English');
}
